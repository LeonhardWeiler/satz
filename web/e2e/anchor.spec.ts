import { expect, test, open, screen } from './util'

test('copied layers pasted into a text anchor at the caret and can be released', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await open(page)
  const layers = page.getByRole('tree', { name: 'Layers' })
  const panel = page.getByRole('complementary', { name: 'Properties' })
  const suns = layers.getByRole('button', { name: 'Sun', exact: true })
  await suns.click()
  await page.keyboard.press('Control+c')
  await layers.getByRole('button', { name: /^Satz sets type/ }).click()
  await page.mouse.dblclick(...(await screen(page, 16, 97)))
  await expect(page.getByRole('textbox', { name: 'Text editor' })).toBeFocused()
  await page.keyboard.press('Control+v')
  await expect(suns).toHaveCount(2)
  await page.keyboard.type('X')
  await expect(layers.getByRole('button', { name: /^XSatz sets type/ })).toBeVisible()
  await page.keyboard.press('Escape')

  const anchoring = panel.getByRole('radiogroup', { name: 'Anchoring' })
  await suns.first().click()
  if (!(await anchoring.isVisible())) await suns.last().click()
  await expect(anchoring.getByRole('radio', { name: 'Inline' })).toHaveAttribute('aria-checked', 'true')
  await anchoring.getByRole('radio', { name: 'Custom' }).click()
  await expect(anchoring.getByRole('radio', { name: 'Custom' })).toHaveAttribute('aria-checked', 'true')
  await panel.getByRole('button', { name: 'Release anchor' }).click()
  await expect(anchoring).toHaveCount(0)
  await expect(layers.getByRole('button', { name: /^XSatz sets type/ })).toBeVisible()
})
