import { expect, test, open, assets } from './util'

test('a grep style of a text style sets its matches in another text style', async ({ page }) => {
  await open(page)
  await page.getByRole('tab', { name: 'Layers' }).click()
  const layer = page.getByRole('tree', { name: 'Layers' }).getByRole('button', { name: /^Satz sets type/ })
  await layer.click()
  const panel = page.getByRole('complementary', { name: 'Properties' })
  await panel.getByTitle('Text style', { exact: true }).first().click()
  await page.getByRole('menuitem', { name: 'New text style' }).click()
  await page.mouse.move(0, 0)
  const size = panel.getByRole('textbox', { name: 'Font size in pt' }).first()
  const before = await size.inputValue()

  const left = await assets(page)
  await left.getByRole('button', { name: 'Add text style' }).click()
  const second = left.getByRole('group', { name: 'Text style 2' })
  await left.getByRole('button', { name: 'Edit Text style 2' }).click()
  const big = second.getByRole('textbox', { name: 'Font size in pt' })
  await big.fill('40')
  await big.press('Enter')
  const first = left.getByRole('group', { name: 'Text style 1' })
  await left.getByRole('button', { name: 'Edit Text style 1' }).click()
  await first.getByRole('button', { name: 'Add GREP style' }).click()
  await expect(first.getByRole('combobox', { name: 'GREP text style 1' })).toHaveText('Text style 2')
  const pattern = first.getByRole('textbox', { name: 'GREP pattern 1' })
  await expect(pattern).toHaveValue('\\d+')
  await pattern.fill('(')
  await pattern.press('Enter')
  await expect(page.getByText('( is no regular expression')).toBeVisible()
  await pattern.fill('Satz')
  await pattern.press('Enter')

  await page.getByRole('tab', { name: 'Layers' }).click()
  await layer.click()
  await expect(size).toHaveValue('Mixed')
  await page.getByRole('tab', { name: 'Assets' }).click()
  await left.getByRole('button', { name: 'Edit Text style 1' }).click()
  await first.getByRole('button', { name: 'Remove GREP style 1' }).click()
  await page.getByRole('tab', { name: 'Layers' }).click()
  await layer.click()
  await expect(size).toHaveValue(before)
})
