test('a gradient takes a stop where its bar is clicked, moves it with the arrow keys and drops stops down to 2', async ({ page }) => {
  await open(page)
  const panel = page.getByRole('complementary', { name: 'Properties' })
  await page.getByRole('tree', { name: 'Layers' }).getByRole('button', { name: 'Rectangle', exact: true }).last().click()
  await panel.getByRole('region', { name: 'Fill' }).getByRole('button', { name: 'Fill color' }).first().click()
  const picker = page.getByRole('dialog', { name: 'Fill color' })
  await picker.getByRole('radio', { name: 'Linear' }).click()
  const remove = picker.getByRole('button', { name: 'Remove stop' })
  const position = picker.getByRole('textbox', { name: 'Stop position in %' })
  await expect(remove).toHaveCount(0)
  const bar = (await picker.locator('.picker-stop-bar').boundingBox())!
  await page.mouse.click(bar.x + bar.width / 4, bar.y + bar.height / 2)
  await expect(picker.getByRole('button', { name: /^Stop \d$/ })).toHaveCount(3)
  await expect(position).toHaveValue(/^2[45]/)
  await picker.getByRole('button', { name: 'Stop 1' }).press('ArrowRight')
  await expect(position).toHaveValue('1')
  await page.keyboard.press('Control+z')
  await expect(position).toHaveValue('0')
  await remove.click()
  await expect(picker.getByRole('button', { name: /^Stop \d$/ })).toHaveCount(2)
  await expect(remove).toHaveCount(0)
})
