test('the text style specimen opens a menu of the styles set at their size, marks overrides and resets or updates the style', async ({ page }) => {
  await open(page)
  const panel = page.getByRole('complementary', { name: 'Properties' })
  await page.getByRole('tree', { name: 'Layers' }).getByRole('button', { name: /^Satz sets type/ }).click()
  await panel.getByTitle('Text style', { exact: true }).first().click()
  await page.getByRole('menuitem', { name: 'New text style' }).click()
  await page.mouse.move(0, 0)
  const specimen = panel.getByTitle('Text style', { exact: true })
  await expect(specimen).toContainText('Text style 1')
  await specimen.click()
  await expect(page.getByRole('menuitemradio', { name: 'Text style 1' })).toBeFocused()
  await page.keyboard.press('Escape')
  const size = panel.getByRole('textbox', { name: 'Font size in pt' }).first()
  await size.fill('30')
  await size.press('Enter')
  await expect(specimen).toContainText('Text style 1*')
  await specimen.click()
  await page.getByRole('menuitem', { name: 'Reset to style' }).click()
  await expect(specimen).not.toContainText('*')
  await size.fill('30')
  await size.press('Enter')
  await specimen.click()
  await page.getByRole('menuitem', { name: 'Update style' }).click()
  await expect(specimen).toContainText('30/')
  await expect(specimen).not.toContainText('*')
  await specimen.click()
  await page.getByRole('menuitemradio', { name: 'No style' }).click()
  await expect(specimen).toContainText('No style')
})

test('a fill is dragged below another to reorder them', async ({ page }) => {
  await open(page)
  const panel = page.getByRole('complementary', { name: 'Properties' })
  await page.getByRole('tree', { name: 'Layers' }).getByRole('button', { name: 'Rectangle', exact: true }).last().click()
  const fills = panel.getByRole('region', { name: 'Fill' })
  await fills.getByRole('button', { name: 'Add fill' }).click()
  await fills.getByRole('button', { name: 'Fill color' }).first().click()
  await page.getByRole('dialog', { name: 'Fill color' }).getByRole('radio', { name: 'Linear' }).click()
  await page.keyboard.press('Escape')
  const angles = (n: number) => fills.getByRole('listitem').nth(n).getByTitle('Fill angle')
  await expect(angles(0)).toHaveCount(1)
  await fills.getByRole('listitem').first().dragTo(fills.getByRole('listitem').last())
  await expect(angles(0)).toHaveCount(0)
  await expect(angles(1)).toHaveCount(1)
})

test('properties the selected layers share are edited together', async ({ page }) => {
  await open(page)
  const panel = page.getByRole('complementary', { name: 'Properties' })
  const layers = page.getByRole('tree', { name: 'Layers' })
  await layers.getByRole('button', { name: 'Sun', exact: true }).click()
  await layers.getByRole('button', { name: 'Triangle', exact: true }).click({ modifiers: ['Control'] })
  await panel.getByRole('textbox', { name: 'Opacity in %', exact: true }).fill('12.5')
  await panel.getByRole('textbox', { name: 'Opacity in %', exact: true }).press('Enter')
  const fill = panel.getByRole('region', { name: 'Fill' })
  await expect(fill).toContainText('Mixed')
  await fill.getByRole('button', { name: 'Add fill' }).click()
  await expect(fill.getByRole('button', { name: 'Fill color' })).toHaveCount(1)
  for (const name of ['Sun', 'Triangle']) {
    await layers.getByRole('button', { name, exact: true }).click()
    await expect(panel.getByRole('textbox', { name: 'Opacity in %', exact: true })).toHaveValue('12.5')
    await expect(fill.getByRole('button', { name: 'Fill color' })).toHaveCount(1)
  }
})

test('focus moved after a click shows no ring until a key is pressed', async ({ page }) => {
  await open(page)
  await page.keyboard.press('Escape')
  const add = page.getByRole('complementary', { name: 'Properties' }).getByRole('button', { name: 'Add layout grid' })
  await add.click()
  await page.getByRole('menu').getByRole('menuitem').first().click()
  await expect(add).toBeFocused()
  await expect(add).toHaveCSS('outline-style', 'none')
  await page.keyboard.press('Shift+Tab')
  await page.keyboard.press('Tab')
  await expect(add).toHaveCSS('outline-style', 'solid')
})

