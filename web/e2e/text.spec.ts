test('a clicked text is auto width, a dragged one a fixed empty box shown while dragging, resizing and shift w or h set the mode and nudging keeps it', async ({ page }) => {
  await open(page)
  const panel = page.getByRole('complementary', { name: 'Properties' })
  const field = (name: string) => panel.getByRole('textbox', { name })
  const mode = (name: string) => panel.getByRole('radio', { name })
  const type = async (name: string, v: string) => {
    await field(name).fill(v)
    await field(name).press('Enter')
  }
  await page.keyboard.press('t')
  await page.mouse.click(...(await screen(page, 20, 80)))
  await expect(mode('Auto width')).toBeChecked()
  await expect(field('W in mm')).toHaveValue('0')
  await expect(field('H in mm')).toHaveValue('5.8')
  await expect(panel.getByRole('combobox', { name: 'Width sizing' })).toHaveCount(0)

  await page.keyboard.press('Escape')
  await page.keyboard.press('t')
  const [x0, y0] = await screen(page, 20, 100)
  await page.mouse.move(x0, y0)
  await page.mouse.down()
  await page.mouse.move(...(await screen(page, 60, 120)), { steps: 4 })
  const edge = await pixels(page, x0 - 3, y0 + 20, 6, 1)
  expect(edge.some(([r, g, b]) => b > 200 && r < 100 && g > 100)).toBe(true)
  await page.mouse.up()
  await expect(mode('Fixed size')).toBeChecked()
  await expect(field('W in mm')).toHaveValue('40')
  await expect(field('H in mm')).toHaveValue('20')
  await expect(page.getByRole('textbox', { name: 'Text editor' })).toBeFocused()
  await page.keyboard.type('Hi')
  await expect(page.getByRole('tree', { name: 'Layers' }).getByRole('button', { name: 'Hi', exact: true })).toBeVisible()
  await expect(field('H in mm')).toHaveValue('20')
  await type('H in mm', '30')
  await expect(mode('Fixed size')).toBeChecked()
  await mode('Auto height').click()
  await expect(field('H in mm')).toHaveValue('5.8')
  await mode('Auto width').click()
  await expect(mode('Auto width')).toBeChecked()
  await expect(field('W in mm')).not.toHaveValue('40')
  const w = await field('W in mm').inputValue()
  const x = Number(await field('X in mm').inputValue())
  await page.evaluate(() => (document.activeElement as HTMLElement).blur())
  await page.keyboard.press('Escape')
  await page.keyboard.press('ArrowRight')
  await expect(field('X in mm')).toHaveValue(String(Math.round(x * 10 + 1) / 10))
  await expect(mode('Auto width')).toBeChecked()
  await expect(field('W in mm')).toHaveValue(w)
  await page.keyboard.press('Shift+H')
  await expect(mode('Auto height')).toBeChecked()
  await page.keyboard.press('Shift+W')
  await expect(mode('Auto width')).toBeChecked()
})

test('a fixed text frame pulled narrower than its text becomes auto height', async ({ page }) => {
  await open(page)
  const panel = page.getByRole('complementary', { name: 'Properties' })
  await page.keyboard.press('t')
  await drag(page, await screen(page, 20, 100), await screen(page, 120, 110))
  await page.keyboard.type('Satz sets type in the browser')
  await page.keyboard.press('Escape')
  await expect(panel.getByRole('radio', { name: 'Fixed size' })).toBeChecked()
  await drag(page, await screen(page, 120, 105), await screen(page, 50, 105))
  await expect(panel.getByRole('radio', { name: 'Auto height' })).toBeChecked()
  await expect(panel.getByRole('textbox', { name: 'W in mm' })).toHaveValue('30')
  await expect(panel.getByRole('textbox', { name: 'H in mm' })).not.toHaveValue('10')
})

