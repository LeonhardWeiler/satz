import { expect, test, drag, open, pixels, screen, choose } from './util'

test('type attributes and a text style are set in the text section and edited on the page', async ({ page }) => {
  await open(page)
  const panel = page.getByRole('complementary', { name: 'Properties' })
  const text = page.getByRole('tree', { name: 'Layers' }).getByRole('button', { name: /^Satz sets type/ })
  const field = (name: string) => panel.getByRole('textbox', { name })
  const commit = async (name: string, value: string) => {
    await field(name).fill(value)
    await field(name).press('Enter')
  }
  await text.click()
  await expect(field('Font size in pt')).toHaveValue('14')
  await expect(field('Line height in pt')).toHaveValue('Auto')
  await expect(panel.getByRole('radio', { name: 'Justify' })).toBeChecked()

  await commit('Font size in pt', '11')
  await commit('Line height in pt', '15')
  await panel.getByRole('radio', { name: 'Align center' }).click()
  await expect(panel.getByRole('radio', { name: 'Align center' })).toBeChecked()
  await panel.getByTitle('Text style', { exact: true }).click()
  await page.getByRole('menuitem', { name: 'Create text style' }).click()
  await page.mouse.move(0, 0)
  await expect(panel.getByTitle('Text style', { exact: true })).toContainText('Text style 1')

  await page.keyboard.press('Escape')
  const style = panel.getByRole('group', { name: 'Text style 1' })
  await expect(style.getByRole('textbox', { name: 'Font size in pt' })).toHaveValue('11')
  await style.getByRole('textbox', { name: 'Font size in pt' }).fill('9')
  await style.getByRole('textbox', { name: 'Font size in pt' }).press('Enter')
  await text.click()
  await expect(field('Font size in pt')).toHaveValue('9')
  await commit('Line height in pt', 'auto')
  await expect(field('Line height in pt')).toHaveValue('Auto')
  await expect(panel.getByTitle('Text style', { exact: true })).toContainText('No style')
  await expect(field('Font size in pt')).toHaveValue('9')
})

test('case, decoration, indent and OpenType features are set in the type options and kept by a text style', async ({ page }) => {
  await open(page)
  const panel = page.getByRole('complementary', { name: 'Properties' })
  const text = page.getByRole('tree', { name: 'Layers' }).getByRole('button', { name: /^Satz sets type/ })
  await text.click()
  await panel.getByRole('button', { name: 'Type options' }).click()
  const options = page.getByRole('dialog', { name: 'Type options' })
  await choose(options.getByRole('combobox', { name: 'Case' }), 'Upper case')
  await choose(options.getByRole('combobox', { name: 'Decoration' }), 'Underline')
  await options.getByRole('textbox', { name: 'Paragraph indent in pt' }).fill('12')
  await options.getByRole('textbox', { name: 'Paragraph indent in pt' }).press('Enter')
  await options.getByRole('checkbox', { name: 'Ligatures', exact: true }).uncheck()
  await options.getByRole('checkbox', { name: 'Oldstyle figures' }).check()
  await page.screenshot({ path: 'test-results/type-options.png' })
  await page.keyboard.press('Escape')
  await expect(options).toHaveCount(0)

  await panel.getByTitle('Text style', { exact: true }).click()
  await page.getByRole('menuitem', { name: 'Create text style' }).click()
  await page.keyboard.press('Escape')
  await panel.getByRole('group', { name: 'Text style 1' }).getByRole('button', { name: 'Type options' }).click()
  await expect(options.getByRole('combobox', { name: 'Case' })).toHaveText('Upper case')
  await expect(options.getByRole('combobox', { name: 'Decoration' })).toHaveText('Underline')
  await expect(options.getByRole('textbox', { name: 'Paragraph indent in pt' })).toHaveValue('12')
  await expect(options.getByRole('checkbox', { name: 'Ligatures', exact: true })).not.toBeChecked()
  await expect(options.getByRole('checkbox', { name: 'Oldstyle figures' })).toBeChecked()
})

