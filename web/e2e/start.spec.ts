import { type Page } from '@playwright/test'
import { expect, test, autosaved, open, pageCount } from './util'

const start = (page: Page) => page.getByRole('dialog', { name: 'New document' })
const home = (page: Page) => page.getByRole('dialog', { name: 'Projects' })
const spreads = (page: Page) => page.getByRole('navigation', { name: 'Spreads' })

test('the projects show at the start, list what was opened and open it again', async ({ page }) => {
  await page.goto('')
  await expect(home(page).getByRole('heading', { name: 'Examples' })).toBeVisible()
  await home(page).getByRole('button', { name: /Satz booklet/ }).click()
  await expect(page).toHaveTitle('booklet.satz - Satz')
  await pageCount(page, 8)
  await autosaved(page, false)
  await page.getByRole('button', { name: 'Projects' }).click()
  await home(page).getByRole('button', { name: /Poster/ }).click()
  await expect(page).toHaveTitle('poster.satz - Satz')
  await autosaved(page, false)
  await page.getByRole('button', { name: 'Projects' }).click()
  const cards = home(page).getByRole('list', { name: 'Recent' }).getByRole('listitem')
  await expect(cards).toHaveCount(3)
  await expect(cards.first()).toContainText('poster')
  await expect(cards.first().locator('img')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page).toHaveTitle('poster.satz - Satz')
  await page.getByRole('button', { name: 'Projects' }).click()
  await cards.getByRole('button', { name: /^booklet/ }).click()
  await expect(page).toHaveTitle('booklet.satz - Satz')
  await pageCount(page, 8)
  await page.reload()
  await expect(page).toHaveTitle('booklet.satz - Satz')
  await page.getByRole('button', { name: 'Projects' }).click()
  await home(page).getByRole('button', { name: 'Delete booklet.satz' }).click()
  await page.locator('.ask').getByRole('button', { name: 'Delete' }).click()
  await expect(cards).toHaveCount(2)
  await page.reload()
  await expect(home(page)).toBeVisible()
})

test('an example that does not load says so and keeps the projects', async ({ page }) => {
  test.info().annotations.push({ type: 'errors' })
  await page.route('**/booklet-*.satz', (r) => r.fulfill({ status: 404 }))
  await page.goto('')
  await home(page).getByRole('button', { name: /Satz booklet/ }).click()
  await expect(page.locator('.status')).toHaveText(/Could not open booklet.satz: 404/)
  await expect(home(page)).toBeVisible()
})

test('enter creates a document of the chosen format, orientation and pages', async ({ page }) => {
  await open(page)
  await page.keyboard.press('Control+Alt+n')
  const dialog = start(page)
  await expect(dialog.getByRole('radio', { name: /A5/ })).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(dialog.getByRole('radio', { name: /A4/ })).toBeFocused()
  await dialog.getByRole('radio', { name: 'Landscape' }).click()
  await dialog.getByRole('textbox', { name: 'Pages' }).fill('3')
  await dialog.getByRole('textbox', { name: 'Pages' }).press('Enter')
  await expect(dialog.getByRole('button', { name: 'Create' })).toHaveAttribute('title', 'A4, 3 pages')
  await dialog.getByRole('radio', { name: /A4/ }).press('Enter')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByText('Created A4, 3 pages')).toBeVisible()
  const panel = page.getByRole('complementary', { name: 'Properties' })
  await expect(panel.getByRole('textbox', { name: 'W in mm' })).toHaveValue('297')
  await expect(panel.getByRole('textbox', { name: 'H in mm' })).toHaveValue('210')
  await expect(panel.getByRole('checkbox', { name: 'Facing pages' })).toBeChecked()
  await expect(spreads(page).getByRole('button', { name: 'Page 1' })).toBeVisible()
})

test('a custom size, color mode, bleed and columns go into the document', async ({ page }) => {
  await open(page)
  await page.keyboard.press('Control+Alt+n')
  const dialog = start(page)
  const fill = async (name: string, v: string) => {
    await dialog.getByRole('textbox', { name }).fill(v)
    await dialog.getByRole('textbox', { name }).press('Tab')
  }
  await dialog.getByRole('radio', { name: 'RGB' }).click()
  await fill('Bleed', '5')
  await fill('Columns', '3')
  await fill('Width', '100')
  await expect(dialog.getByRole('radio', { checked: true, name: /A5/ })).toHaveCount(0)
  await dialog.getByRole('textbox', { name: 'Width' }).press('Tab')
  await dialog.getByRole('textbox', { name: 'Pages' }).fill('1')
  await dialog.getByRole('textbox', { name: 'Pages' }).press('Tab')
  await expect(dialog.getByRole('checkbox', { name: 'Facing pages' })).toBeDisabled()
  await dialog.getByRole('button', { name: /Create/ }).click()
  const panel = page.getByRole('complementary', { name: 'Properties' })
  await expect(panel.getByRole('textbox', { name: 'W in mm' })).toHaveValue('100')
  await expect(panel.getByRole('textbox', { name: 'Bleed in mm' })).toHaveValue('5')
  await expect(panel.getByRole('combobox', { name: 'Color mode' })).toHaveText(/RGB$/)
  await expect(panel.getByRole('textbox', { name: 'Columns' })).toHaveValue('3')
})

test('a new document preset is saved, picked after a reload and deleted', async ({ page }) => {
  await open(page)
  await page.keyboard.press('Control+Alt+n')
  const dialog = start(page)
  await dialog.getByRole('radio', { name: /A4/ }).click()
  await dialog.getByRole('textbox', { name: 'Pages' }).fill('12')
  await dialog.getByRole('textbox', { name: 'Pages' }).press('Tab')
  await dialog.getByRole('textbox', { name: 'Preset name' }).fill('Report')
  await dialog.getByRole('button', { name: 'Save preset' }).click()
  await page.reload()
  await expect(page.getByLabel('Zoom')).not.toHaveText('0%')
  const projects = page.getByRole('dialog', { name: 'Projects' })
  if (await projects.isVisible()) await projects.getByRole('button', { name: 'New document' }).click()
  else await page.keyboard.press('Control+Alt+n')
  const saved = dialog.getByRole('radiogroup', { name: 'Saved presets' })
  await saved.getByRole('radio', { name: /Report/ }).click()
  await expect(dialog.getByRole('textbox', { name: 'Pages' })).toHaveValue('12')
  await expect(dialog.getByRole('button', { name: 'Create' })).toHaveAttribute('title', 'A4, 12 pages')
  await saved.getByRole('button', { name: 'Delete preset Report' }).click()
  await expect(saved).toHaveCount(0)
})

test('escape returns to the document and new keeps the changes in their project', async ({ page }) => {
  await open(page)
  await page.getByRole('tree', { name: 'Layers' }).getByRole('button', { name: 'Sun' }).click()
  await page.keyboard.press('Delete')
  await page.keyboard.press('Control+Alt+n')
  await page.keyboard.press('Escape')
  await expect(start(page)).toHaveCount(0)
  await expect(page).toHaveTitle('* Untitled.satz - Satz')
  await page.keyboard.press('Control+Alt+n')
  await start(page).getByRole('button', { name: /Create/ }).click()
  await expect(page).toHaveTitle('Untitled.satz - Satz')
  await page.getByRole('button', { name: 'Projects' }).click()
  await expect(home(page).getByRole('list', { name: 'Recent' }).getByRole('listitem')).toHaveCount(3)
})

test('ctrl+o on the start screen opens the file it asks for', async ({ page }) => {
  await page.addInitScript(() => delete (window as { showOpenFilePicker?: unknown }).showOpenFilePicker)
  await open(page)
  await page.keyboard.press('Control+Alt+n')
  const chooser = page.waitForEvent('filechooser')
  await page.keyboard.press('Control+o')
  await (await chooser).setFiles(`${import.meta.dirname}/../../examples/poster.satz`)
  await expect(page).toHaveTitle('poster.satz - Satz')
})
