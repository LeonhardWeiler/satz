import { example, expect, layers, opened, png, props, rest, select, shot, start, test } from './lib'
import { place } from '../e2e/util'

const G = '09 Pages & masters'
const L = '08 Layers & swatches'
const F = '10 Preflight & export'
const ov = (page) => page.getByRole('region', { name: 'Page overview' })
const sw = (page) => page.getByRole('navigation', { name: 'Spreads' })

test('overview', async ({ page }) => {
  await example(page, 'booklet.satz')
  await shot(page, G, '01 switcher, first page', 'Spread switcher on the first page', [sw(page)], 8)
  await page.keyboard.press('PageDown')
  await rest(page)
  await shot(page, G, '02 switcher, a spread', 'Spread switcher on a spread', [sw(page)], 8)
  await page.keyboard.press('End')
  await rest(page)
  await shot(page, G, '03 switcher, last spread', 'Last spread: Add page instead of next', [sw(page)], 8)
  await page.keyboard.press('Home')
  await page.keyboard.press('.')
  await rest(page)
  await shot(page, G, '10 page overview', 'Page overview (.) with masters and spreads')
  const pages = ov(page).getByRole('listbox', { name: 'Pages' })
  await pages.getByRole('option', { name: 'Page 3', exact: true }).click({ modifiers: ['Control'] }).catch(() => {})
  await pages.getByRole('option', { name: 'Page 4', exact: true }).click({ modifiers: ['Shift'] })
  await rest(page)
  await shot(page, G, '11 page overview, selection', 'Pages selected in the overview')
  await pages.getByRole('option', { name: 'Page 4', exact: true }).click({ button: 'right' })
  await shot(page, G, '12 page context menu', 'Page context menu', [pages.getByRole('option', { name: 'Page 4', exact: true }), page.getByRole('menu')], 16)
  await page.keyboard.press('Escape')
  const masters = ov(page).getByRole('listbox', { name: 'Masters' })
  await masters.getByRole('option').first().click({ button: 'right' })
  await shot(page, G, '13 master context menu', 'Master context menu', [masters.getByRole('option').first(), page.getByRole('menu')], 16)
  await page.keyboard.press('Escape')
  const box = (await pages.getByRole('option', { name: 'Page 5', exact: true }).boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2 + 20, box.y + 10, { steps: 4 })
  await page.mouse.move(box.x - 10, box.y - box.height / 2, { steps: 6 })
  await shot(page, G, '14 dragging a page', 'Dragging a page: drop indicator')
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await page.keyboard.press('Control+z').catch(() => {})
  const ob = (await ov(page).boundingBox())!
  await page.mouse.move(ob.x + ob.width - 40, ob.y + ob.height - 40)
  await page.mouse.down()
  await page.mouse.move(ob.x + ob.width - 300, ob.y + ob.height - 400, { steps: 6 })
  await shot(page, G, '15 overview marquee', 'Marquee band in the page overview')
  await page.mouse.up()
  await ov(page).getByRole('spinbutton', { name: 'Columns' }).or(ov(page).getByRole('textbox', { name: 'Columns' })).fill('3')
  await page.keyboard.press('Enter')
  await rest(page)
  await shot(page, G, '16 overview, 3 columns', 'Page overview with 3 columns of spreads')
  await masters.getByRole('option').first().click({ button: 'right' })
  await page.getByRole('menu').getByRole('menuitem', { name: 'Rename' }).click()
  await shot(page, G, '17 master rename', 'Master being renamed', [masters], 8)
  await page.keyboard.press('Escape')
  await shot(page, G, '18 masters column', 'Masters column', [masters], 8)
})

