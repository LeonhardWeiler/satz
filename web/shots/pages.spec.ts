test('layers', async ({ page }) => {
  await start(page)
  await shot(page, L, '01 layers', 'Layers tree', ['left'])
  const row = (n: string) => layers(page).getByRole('treeitem', { name: n }).first()
  await select(page, 'Star')
  await row('Star').hover()
  await shot(page, L, '02 layer hover and selected', 'Selected row and the hover actions (lock, eye)', ['left'])
  await row('Triangle').hover()
  await row('Triangle').getByRole('button', { name: 'Hide' }).click()
  await row('Sun').hover()
  await row('Sun').getByRole('button', { name: 'Lock' }).click()
  await select(page, 'Arrow', 'Blurred tile')
  await shot(page, L, '03 hidden, locked, multi selection', 'Hidden layer (Triangle), locked layer (Sun), several selected', ['left'])
  await shot(page, '04 Canvas', '70 hidden and locked layers', 'Canvas with a hidden and a locked layer')
  await layers(page).locator('.layer-name').filter({ hasText: /^Arrow$/ }).dblclick()
  await shot(page, L, '04 layer rename', 'Layer being renamed', ['left'])
  await page.keyboard.press('Escape')
  const from = (await layers(page).locator('.layer-name').filter({ hasText: /^Star$/ }).boundingBox())!
  const to = (await layers(page).locator('.layer-name').filter({ hasText: /^Frame$/ }).boundingBox())!
  await page.mouse.move(from.x + 10, from.y + 5)
  await page.mouse.down()
  await page.mouse.move(to.x + 10, to.y + 2, { steps: 6 })
  await shot(page, L, '07 drag, drop above', 'Dragging a layer: drop above', ['left'])
  await page.mouse.move(to.x + 10, to.y + to.height / 2, { steps: 3 })
  await shot(page, L, '08 drag, drop into', 'Dragging a layer: drop into a frame', ['left'])
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await page.keyboard.press('Control+z')
  await layers(page).getByRole('button', { name: 'Collapse' }).first().click()
  await rest(page)
  await shot(page, L, '09 collapsed group', 'Collapsed group', ['left'])
  await layers(page).locator('.layer-name').filter({ hasText: /^Frame$/ }).click({ button: 'right' })
  await shot(page, L, '10 layer context menu', 'Context menu on a layer row', ['left', page.getByRole('menu')], 0)
})

