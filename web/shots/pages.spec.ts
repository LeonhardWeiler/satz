test('preflight rgb', async ({ page }) => {
  await start(page, { h: 1200 })
  await page.keyboard.press('Control+Alt+y')
  await rest(page)
  const pf = page.getByRole('region', { name: 'Preflight' })
  await shot(page, F, '01 preflight, no issues', 'Preflight without issues (RGB)')
  await shot(page, F, '02 preflight panel, no issues', 'Preflight panel without issues', ['right'])
  await opened(page, F, '03 format select', 'Export format select', pf.getByRole('combobox', { name: 'Format' }))
  await opened(page, F, '04 preset select', 'Preset select in an RGB document (X-1a disabled)', pf.getByRole('combobox', { name: 'Preset' }))
  for (const [i, f] of [['05', 'PNG'], ['06', 'JPEG'], ['07', 'Package']] as const) {
    await pf.getByRole('combobox', { name: 'Format' }).click()
    await page.getByRole('menu').getByRole('menuitemradio', { name: new RegExp(`^${f}`) }).click()
    await rest(page)
    await shot(page, F, `${i} export as ${f}`, `Export section for ${f}`, [pf.getByRole('region', { name: 'Export' })], 8)
  }
  await pf.getByRole('textbox', { name: 'Pages to export' }).fill('7-x')
  await shot(page, F, '08 invalid page range', 'Invalid page range disables the export', [pf.getByRole('region', { name: 'Export' })], 8)
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+Alt+y')
  await select(page, 'Satz sets type…')
  await props(page).getByRole('textbox', { name: /^H\b/ }).first().fill('15')
  await page.keyboard.press('Enter')
  await place(page, png('small.png', 20, 20, (x, y) => [x * 10, y * 10, 80]), [74, 150])
  await props(page).getByRole('textbox', { name: /^W\b/ }).first().fill('80')
  await page.keyboard.press('Enter')
  await page.keyboard.press('Escape')
  await rest(page)
  await shot(page, F, '10 preflight button with errors', 'Top bar preflight count with errors', [page.locator('header.bar .end')], 8)
  await page.keyboard.press('Control+Alt+y')
  await rest(page)
  await shot(page, F, '11 preflight with issues', 'Preflight with errors and warnings')
  await shot(page, F, '12 preflight panel with issues', 'Preflight panel with issues', ['right'])
  await pf.locator('.iss').first().click()
  await rest(page)
  await shot(page, F, '13 issue selected', 'An issue clicked: its layer selected and shown')
})

test('preflight cmyk', async ({ page }) => {
  await example(page, 'poster.satz', { h: 1200 })
  await page.keyboard.press('Control+Alt+y')
  await page.keyboard.press('Shift+1')
  await rest(page)
  const pf = page.getByRole('region', { name: 'Preflight' })
  await expect(pf.getByText('Highest')).toBeVisible()
  await page.waitForTimeout(1500)
  await shot(page, F, '20 preflight CMYK', 'Preflight of a CMYK document: proof, separations, ink coverage')
  await shot(page, F, '21 preflight CMYK panel', 'Preflight panel (CMYK)', ['right'])
  await pf.getByRole('checkbox', { name: 'Mark colours outside the gamut' }).check()
  await page.waitForTimeout(1500)
  await shot(page, F, '22 gamut marks', 'Colours outside the gamut marked on the canvas')
  await pf.getByRole('checkbox', { name: 'Mark colours outside the gamut' }).check()
  await pf.getByText('Mark above limit').click()
  await pf.getByRole('textbox', { name: 'Ink limit' }).fill('200')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(1500)
  await shot(page, F, '23 ink above limit', 'Ink above the limit marked on the canvas')
  await pf.getByText('Mark above limit').click()
  const plates = pf.getByRole('region', { name: 'Separations' }).locator('.plate')
  await plates.first().click()
  await page.waitForTimeout(1500)
  await shot(page, F, '24 cyan plate off', 'Separations with the cyan plate turned off')
  await plates.first().click()
  await plates.last().click()
  await page.waitForTimeout(1500)
  await shot(page, F, '25 cyan and spot plates off', 'Separations with the cyan and the spot plate turned off')
  await plates.last().click()
  const c = (await page.getByLabel('Page canvas').boundingBox())!
  await page.mouse.move(c.x + c.width / 2, c.y + c.height * 0.55)
  await page.waitForTimeout(800)
  await shot(page, F, '26 ink under pointer', 'Ink coverage under the pointer', [pf.getByRole('region', { name: 'Ink coverage' })], 8)
  await rest(page)
  await opened(page, F, '27 preset select CMYK', 'Preset select in a CMYK document', pf.getByRole('combobox', { name: 'Preset' }))
  await pf.locator('.pf-go').click()
  await shot(page, F, '28 exporting', 'Exporting: button and progress bar', [pf.getByRole('region', { name: 'Export' })], 8)
  await page.waitForTimeout(5000)
  await shot(page, F, '29 exported', 'After the export: status line', [page.locator('.status'), pf.getByRole('region', { name: 'Export' })], 8)
})
