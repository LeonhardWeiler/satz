test('anchor and condition', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await start(page)
  await select(page, 'Sun')
  await page.keyboard.press('Control+c')
  await select(page, 'Satz sets type in th…')
  await page.mouse.dblclick(...(await screen(page, 40, 97)))
  await expect(page.getByRole('textbox', { name: 'Text editor' })).toBeFocused()
  await page.keyboard.press('Home')
  await page.keyboard.press('Control+v')
  const suns = layers(page).getByRole('button', { name: 'Sun', exact: true })
  await expect(suns).toHaveCount(2)
  await page.keyboard.press('Escape')
  await suns.first().click()
  if (!(await props(page).getByRole('radiogroup', { name: 'Anchoring' }).isVisible())) await suns.last().click()
  await rest(page)
  await shot(page, F, '30 anchored layer', 'Properties of an anchored layer', ['right'])
  await addVariable(page, 'Boolean')
  await page.keyboard.press('Escape')
  await page.getByRole('tab', { name: 'Layers' }).click()
  await layers(page).getByRole('button', { name: /Satz sets type/ }).click()
  await rest(page)
  const condition = props(page).getByRole('combobox', { name: 'Condition' })
  await choose(condition, 'Boolean 1')
  await rest(page)
  await shot(page, F, '31 condition', 'Text with a condition', ['right'])
  await expect(condition).toHaveText(/Boolean 1/)
})
