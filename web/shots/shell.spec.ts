test('dialogs', async ({ page }) => {
  await start(page)
  await page.keyboard.press('?')
  const help = page.getByRole('dialog', { name: 'Keyboard shortcuts' })
  await shot(page, D, '10 keyboard shortcuts', 'Keyboard shortcuts (?)')
  await help.getByRole('textbox', { name: 'Search shortcuts' }).fill('zoom')
  await shot(page, D, '11 keyboard shortcuts, search', 'Shortcuts filtered by a search', [help])
  await help.getByRole('textbox', { name: 'Search shortcuts' }).fill('xyzzy')
  await shot(page, D, '12 keyboard shortcuts, no match', 'No shortcut matches', [help])
  await help.getByRole('textbox', { name: 'Search shortcuts' }).fill('')
  await help.getByRole('button', { name: /^Shortcut for / }).first().click()
  await shot(page, D, '13 keyboard shortcuts, recording', 'Recording a new shortcut ("Press keys")', [help])
  await page.keyboard.press('Control+Alt+j')
  await shot(page, D, '14 keyboard shortcuts, remapped', 'A remapped shortcut shows Reset shortcuts', [help])
  await page.keyboard.press('Escape')
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+,')
  const settings = page.getByRole('dialog', { name: 'Settings' })
  await shot(page, D, '20 settings', 'Settings (Ctrl+,)')
  await shot(page, D, '21 settings, close-up', 'Settings, close-up', [settings])
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+k')
  const pal = page.getByRole('dialog', { name: 'Command palette' })
  await shot(page, D, '30 command palette', 'Command palette (Ctrl+K)')
  await pal.getByRole('combobox').or(pal.getByRole('textbox')).first().fill('st')
  await shot(page, D, '31 command palette, search', 'Palette search across commands, layers, pages, swatches', [pal])
  await pal.getByRole('combobox').or(pal.getByRole('textbox')).first().fill('xyzzy')
  await shot(page, D, '32 command palette, nothing', 'Palette with nothing matching', [pal])
  await page.keyboard.press('Escape')
  await page.keyboard.press('Control+f')
  const find = page.getByRole('dialog', { name: 'Find and replace' }).or(page.getByRole('search', { name: 'Find and replace' })).or(page.getByLabel('Find and replace'))
  await shot(page, D, '40 find', 'Find and replace (Ctrl+F)')
  await page.getByRole('textbox', { name: 'Find', exact: true }).fill('the')
  await shot(page, D, '41 find, matches', 'Find with matches highlighted on the canvas')
  await shot(page, D, '42 find, close-up', 'Find and replace, close-up', [find.first()], 24)
  await page.getByRole('textbox', { name: 'Find', exact: true }).fill('xyzzy')
  await shot(page, D, '43 find, no match', 'Find with no match', [find.first()], 24)
})

